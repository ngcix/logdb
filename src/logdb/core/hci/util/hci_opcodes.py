def get_command_name(opcode: int) -> str:
    """Return the command name for an opcode, or a placeholder if unknown."""
    name = HCI_COMMANDS.get(opcode)
    if name:
        return name
    if opcode >> 10 == 0x3F:  # OGF 0x3F is the vendor specific group
        return f"Vendor_Command_0x{opcode:04x}"
    return f"Unknown_Command_0x{opcode:04x}"


def get_event_name(event_code: int) -> str:
    """Return the event name for an event code, or a placeholder if unknown."""
    return HCI_EVENTS.get(event_code, f"Unknown_Event_0x{event_code:02x}")


def get_subevent_name(subevent_code: int) -> str:
    """Return the LE meta subevent name, or a placeholder if unknown."""
    return LE_META_SUBEVENT_CODES.get(
        subevent_code, f"Unknown_LE_Subevent_0x{subevent_code:02x}")


def get_status_name(status_code: int) -> str:
    """Return the error/status name for a status code."""
    return BT_STATUS_CODES.get(status_code, f"Unknown_0x{status_code:02x}")
